D.fmt = n => {
  if (n < 1000) return (n < 10 && n % 1 ? n.toFixed(1) : Math.floor(n)) + '';
  const u = ['', 'K', 'M', 'B', 'T']; let i = 0;
  while (n >= 1000 && i < u.length - 1) { n /= 1000; i++; }
  return (n < 10 ? n.toFixed(2) : n < 100 ? n.toFixed(1) : Math.floor(n)) + u[i];
};
